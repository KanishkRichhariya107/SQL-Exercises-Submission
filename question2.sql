WITH employee_hours AS (
SELECT
e.id,
e.name,
SUM(a.hours_logged) AS total_hours
FROM employees e
JOIN assignments a
ON a.employee_id = e.id
GROUP BY e.id, e.name
)
SELECT name, total_hours
FROM employee_hours
WHERE total_hours > (
SELECT AVG(total_hours)
FROM employee_hours
)
ORDER BY total_hours DESC;

