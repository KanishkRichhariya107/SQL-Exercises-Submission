SELECT
    p.id AS project_id,
    p.name AS project_name,
    d.name AS department,
    p.status,
    COUNT(DISTINCT a.employee_id) AS team_size,
    COALESCE(SUM(a.hours_logged), 0) AS total_hours
FROM projects p
JOIN departments d
ON d.id = p.department_id
LEFT JOIN assignments a
ON a.project_id = p.id
GROUP BY p.id, p.name, d.id, d.name, p.status
ORDER BY total_hours DESC, p.id;

