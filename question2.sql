WITH ranked_employees AS (
    SELECT
        e.id,
        e.name,
        e.department_id,
        e.salary,
        DENSE_RANK() OVER (
            PARTITION BY e.department_id
            ORDER BY e.salary DESC
        ) AS salary_rank
    FROM employees e
)
SELECT
    re.name AS employee_name,
    d.name AS department,
    re.salary
FROM ranked_employees re
JOIN departments d
ON d.id = re.department_id
WHERE re.salary_rank = 2
ORDER BY d.name, re.salary DESC;

