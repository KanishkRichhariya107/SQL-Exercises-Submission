SELECT e.id, e.name
FROM employees e
WHERE NOT EXISTS (
    SELECT 1
    FROM assignments a
    JOIN projects p
    ON p.id = a.project_id
    WHERE a.employee_id = e.id
    AND p.status = 'active'
)
ORDER BY e.id;

