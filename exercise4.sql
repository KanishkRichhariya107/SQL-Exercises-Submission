--QUERRY 5

WITH ranked_article AS (
    SELECT a.article_id, a.article_name, COUNT(c.comment_id) AS total_comments
    FROM articles AS a
    LEFT JOIN comments AS c
        ON a.article_id = c.article_id 
    GROUP BY a.article_id, a.article_name
)
SELECT * 
from ranked_article
where total_comments = (
    SELECT max(total_comments)
    FROM ranked_article
);


