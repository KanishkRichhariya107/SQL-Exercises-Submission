--1. Find the third-highest distinct salary in the company.

select * from 
(
  select e.*, dense_rank() over( order by salary DESC ) as rank_salary
  from employees as e
) as ranked_salary
where
rank_salary = 3;

--2. Find the highest-paid employee in every department.

select * from 
(
  select e.*, dense_rank() over( partition by department order by salary DESC ) as rank_salary
  from employees as e
) as ranked_salary
where rank_salary = 1;

--3. Show each employee's salary and the department's average salary.

select e.* , AVG(salary) over( partition by department ) as avg_rank
from employees as e;

--4. Show each employee's salary and the difference from the previous employee by ID.

select e.* , salary - LAG(salary,1,0) over( order by id ) as salary_difference
from employees as e;

--5. Calculate a running salary total by ID.

select e.* ,SUM(salary) over( order by id ) as SUM_TILL_NOW
from employees as e;

--6. Find employees whose salary is above their department average.

select *
from (
 select e.*, AVG(salary) over( partition by department ) as avg_dept from employees as e
) as dept_avg_table
where salary >= avg_dept;
