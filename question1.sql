WITH order_totals AS (
    SELECT
        o.id AS order_id,
        SUM(oi.quantity * oi.unit_price) AS order_value
    FROM orders o
    JOIN order_items oi
    ON oi.order_id = o.id
    WHERE o.status <> 'cancelled'
    GROUP BY o.id
),
ranked_orders AS (
    SELECT
        order_id,
        order_value,
        DENSE_RANK() OVER (
            ORDER BY order_value DESC
        ) AS value_rank
    FROM order_totals
)
SELECT order_id, order_value
FROM ranked_orders
WHERE value_rank = 2;


