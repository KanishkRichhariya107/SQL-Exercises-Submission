WITH months AS (
    SELECT GENERATE_SERIES(
        DATE '2026-01-01',
        DATE '2026-05-01',
        IN TERVAL '1 month'
    )::date AS month_start
),
monthly_revenue AS (
    SELECT
        DATE_TRUNC('month', o.ordered_date)::date AS month_start,
        SUM(oi.quantity * oi.unit_price) AS revenue
    FROM orders o
    JOIN order_items oi
    ON oi.order_id = o.id
    WHERE o.status = 'delivered'
    AND o.ordered_date >= DATE '2026-01-01'
    AND o.ordered_date < DATE '2026-06-01'
    GROUP BY DATE_TRUNC('month', o.ordered_date)::date
)
SELECT
    TO_CHAR(m.month_start, 'Mon YYYY') AS month,
    COALESCE(r.revenue, 0) AS revenue
FROM months m
LEFT JOIN monthly_revenue r
ON r.month_start = m.month_start
ORDER BY m.month_start;


