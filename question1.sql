WITH ranked_orders AS (
    SELECT
        c.name,
        o.id AS order_id,
        o.ordered_date,
        o.status,
        COALESCE(
            SUM(oi.quantity * oi.unit_price),
            0
        ) AS order_total,
        ROW_NUMBER() OVER (
            PARTITION BY c.id
            ORDER BY o.ordered_date DESC, o.id DESC
        ) AS rn
    FROM customers c
    JOIN orders o
    ON o.customer_id = c.id
    LEFT JOIN order_items oi
    ON oi.order_id = o.id
    GROUP BY
        c.id, c.name, o.id, o.ordered_date, o.status
)
SELECT
    name,
    order_id,
    ordered_date,
    status,
    order_total
FROM ranked_orders
WHERE rn = 1
ORDER BY order_id;


