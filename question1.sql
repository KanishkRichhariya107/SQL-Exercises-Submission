SELECT
    COALESCE(c.city, 'Unknown') AS city,
    COUNT(DISTINCT c.id) AS number_of_customers,
    COUNT(o.id) FILTER (
        WHERE o.status = 'delivered'
    ) AS delivered_orders
FROM customers c
LEFT JOIN orders o
ON o.customer_id = c.id
GROUP BY COALESCE(c.city, 'Unknown')
ORDER BY city;




