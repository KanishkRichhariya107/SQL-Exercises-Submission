SELECT
    p.category,
    SUM(oi.quantity * oi.unit_price) AS revenue
FROM products p
JOIN order_items oi
ON oi.product_id = p.id
JOIN orders o
ON o.id = oi.order_id
WHERE o.status = 'delivered'
GROUP BY p.category
HAVING SUM(oi.quantity * oi.unit_price) > 3000
ORDER BY revenue DESC;

